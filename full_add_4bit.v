// ============================================================
// 4位元全加器模組 (4-bit Full Adder)
// ============================================================
// 功能描述:
//   本模組透過級聯4個1位全加器，實現4位元加法運算。
//   這種結構稱為"行波進位加法器"(Ripple Carry Adder)。
//   原理是將前一級的進位輸出級聯到後一級的進位輸入。
//
// 架構說明:
//   +-------+     +-------+     +-------+     +-------+
//   |  FA0  |---->|  FA1  |---->|  FA2  |---->|  FA3  |---->Cout
//   | (第0級) |     | (第1級) |     | (第2級) |     | (第3級) |
//   +-------+     +-------+     +-------+     +-------+
//     A0,B0       A1,B1         A2,B2         A3,B3
//     Cin            ↓            ↓            ↓
//
// 時序延遲分析:
//   - 最差情況 (Worst Case): 進位需要通過所有4級
//   - 總延遲 ≈ 4 × (單級進位延遲)
//   - 適合小位寬應用 (≤16位)
//
// 計算範圍:
//   - 輸入範圍: 0 ~ 15 (4位無符號數)
//   - 輸出範圍: 0 ~ 31 (包含進位的5位結果)
// ============================================================
module full_adder_4bit (
    input   [3:0] A,        // 4位元輸入 A (被加數)
                            //   A[0] 為最低有效位 (LSB)
                            //   A[3] 為最高有效位 (MSB)
    
    input   [3:0] B,        // 4位元輸入 B (加數)
                            //   B[0] 為最低有效位 (LSB)
                            //   B[3] 為最高有效位 (MSB)
    
    input         Cin,      // 進位輸入
                            //   一般用於連接多個4位加法器時使用
                            //   或用於加1操作 (遞增1)
    
    output  [3:0] Sum,      // 4位元和輸出 (加法結果的低4位)
                            //   Sum[0] 為最低有效位 (LSB)
                            //   Sum[3] 為最高有效位 (MSB)
    
    output        Cout      // 進位輸出 (溢位標誌)
                            //   當兩個4位數相加產生進位時，Cout=1
                            //   表示結果超過15，需要5位來表示
);

    // ====================================================
    // 內部信號聲明
    // ====================================================
    // carry[3:0] 用於連接各級全加器之間的進位
    // carry[0] 接收外部進位輸入 Cin
    // carry[1] 連接 FA0 的輸出進位到 FA1 的輸入進位
    // carry[2] 連接 FA1 的輸出進位到 FA2 的輸入進位
    // carry[3] 連接 FA2 的輸出進位到 FA3 的輸入進位
    // Cout 接收 FA3 的輸出進位
    wire [3:0] carry;
    
    // ====================================================
    // 進位傳播路徑初始化
    // ====================================================
    // 將外部進位輸入 Cin 分配給第0級全加器的進位輸入
    assign carry[0] = Cin;
    
    // ====================================================
    // 第0級全加器 (處理最低有效位)
    // ====================================================
    // 實例化第一個1位全加器
    // 負責計算最低位 (第0位) 的和與進位
    // 輸入: A[0] (被加數最低位)、B[0] (加數最低位)、Cin (外部進位)
    // 輸出: Sum[0] (結果最低位)、carry[1] (進位到第1級)
    full_adder_1bit FA0 (
        .a(A[0]),
        .b(B[0]),
        .cin(carry[0]),
        .sum(Sum[0]),
        .cout(carry[1])
    );
    
    // ====================================================
    // 第1級全加器
    // ====================================================
    // 實例化第二個1位全加器
    // 負責計算第1位的和與進位
    // 進位輸入來自第0級的進位輸出 (carry[1])
    // 進位輸出送往第2級 (carry[2])
    full_adder_1bit FA1 (
        .a(A[1]),
        .b(B[1]),
        .cin(carry[1]),
        .sum(Sum[1]),
        .cout(carry[2])
    );
    
    // ====================================================
    // 第2級全加器
    // ====================================================
    // 實例化第三個1位全加器
    // 負責計算第2位的和與進位
    // 進位輸入來自第1級的進位輸出 (carry[2])
    // 進位輸出送往第3級 (carry[3])
    full_adder_1bit FA2 (
        .a(A[2]),
        .b(B[2]),
        .cin(carry[2]),
        .sum(Sum[2]),
        .cout(carry[3])
    );
    
    // ====================================================
    // 第3級全加器 (處理最高有效位)
    // ====================================================
    // 實例化第四個1位全加器
    // 負責計算最高位 (第3位) 的和與進位
    // 進位輸入來自第2級的進位輸出 (carry[3])
    // 進位輸出 (Cout) 為最終的溢位信號
    full_adder_1bit FA3 (
        .a(A[3]),
        .b(B[3]),
        .cin(carry[3]),
        .sum(Sum[3]),
        .cout(Cout)
    );

endmodule
