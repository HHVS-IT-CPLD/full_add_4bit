module full_adder_1bit (
    input   a,          // 第一個輸入位元 (被加數)
    input   b,          // 第二個輸入位元 (加數)
    input   cin,        // 進位輸入 (來自前一級的進位)
    output  sum,        // 和輸出 (當前位的計算結果)
    output  cout        // 進位輸出 (送往下一級的進位信號)
);

    // ====================================================
    // 邏輯方程推導:
    // ====================================================
    // 對於1位全加器，邏輯方程如下:
    //
    // Sum的計算 (三個輸入進行異或運算):
    //   sum = A XOR B XOR Cin
    //   邏輯含義: 當輸入1的個數為奇數時，sum=1；為偶數時，sum=0
    //
    // Cout的計算 (多數採樣):
    //   cout = (A AND B) OR (B AND Cin) OR (A AND Cin)
    //   邏輯含義: 當至少有兩個輸入為1時，進位為1
    //   另一種表示方法: cout = (A AND B) OR (Cin AND (A XOR B))
    // ====================================================
    
    // 使用連續指定語句實現全加器邏輯
    assign sum  = a ^ b ^ cin;
    assign cout = (a & b) | (b & cin) | (a & cin);

endmodule